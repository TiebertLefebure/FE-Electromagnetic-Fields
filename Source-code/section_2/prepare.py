"""Generate shared Gmsh/GetDP constants from the established Section 1 inputs."""
from pathlib import Path
import json
from math import sqrt, pi

HERE = Path(__file__).resolve().parent
PARAMETERS = HERE.parent / 'section_1'
SHARED = HERE.parent / 'shared'

def prepare():
    p = json.loads((PARAMETERS / 'cable_inputs.json').read_text())
    m = json.loads((SHARED / 'materials.json').read_text())
    assert p['installation'] == 'direct_buried_touching_trefoil'
    r0 = p['conductor_diameter_mm'] / 2000
    r1 = r0 + p['inner_semiconductor_mm'] / 1000
    r2 = r1 + p['xlpe_mm'] / 1000
    r3 = r2 + p['outer_semiconductor_mm'] / 1000
    r5 = p['diameter_over_copper_mm'] / 2000
    r4 = sqrt(r5*r5-p['copper_area_mm2']*1e-6/pi)
    assert r0 < r1 < r2 < r3 < r4 < r5
    constants = dict(R0=r0, R1=r1, R2base=r2, R3base=r3, R4base=r4,
                     CableDiameter=p['single_cable_diameter_mm']/1000,
                     Vpeak=p['line_voltage_rms_V']*sqrt(2/3),
                     Eps0=m['vacuum_permittivity_F_m'],
                     EpsXLPE=m['xlpe']['relative_permittivity'],
                     SigXLPE=m['xlpe']['conductivity_S_m'],
                     EpsSC=m['semiconductor']['relative_permittivity'],
                     SigSC=m['semiconductor']['conductivity_S_m'],
                     EpsVoid=m['void']['relative_permittivity'],
                     SigVoid=m['void']['conductivity_S_m'])
    text = '// Generated by prepare.py. SI units; edit section_1/cable_inputs.json and shared/materials.json.\n'
    text += '\n'.join(f'{key} = {value:.16g};' for key,value in constants.items())+'\n'
    (HERE / 'parameters.inc').write_text(text)
    return p,m

if __name__ == '__main__':
    prepare()
