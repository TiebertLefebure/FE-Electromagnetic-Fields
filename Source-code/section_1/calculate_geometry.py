"""Derive the directly buried trefoil geometry using the standard library."""
from pathlib import Path
from math import pi, sqrt, log, hypot
import json

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
p = json.loads((HERE / 'cable_inputs.json').read_text())
assert p['installation'] == 'direct_buried_touching_trefoil'
r0 = p['conductor_diameter_mm'] / 2
r1 = r0 + p['inner_semiconductor_mm']
r2 = r1 + p['xlpe_mm']
r3 = r2 + p['outer_semiconductor_mm']
r5 = p['diameter_over_copper_mm'] / 2
r4 = sqrt(r5*r5 - p['copper_area_mm2']/pi)
r6 = p['single_cable_diameter_mm'] / 2
D = 2*r6
centres = {'A': [0, D/sqrt(3)], 'B': [-D/2, -D/(2*sqrt(3))],
           'C': [D/2, -D/(2*sqrt(3))]}
assert r0 < r1 < r2 < r3 < r4 < r5 < r6
assert abs(pi*(r5*r5-r4*r4) - p['copper_area_mm2']) < 1e-9
for first, second in [('A', 'B'), ('B', 'C'), ('C', 'A')]:
    a, b = centres[first], centres[second]
    assert abs(hypot(a[0]-b[0], a[1]-b[1])-D) < 1e-9
assert all(p['burial_axis_depth_m']*1000-y > r6 for x, y in centres.values())
values = {
    'installation': p['installation'],
    'phase_radii_mm': [r0, r1, r2, r3, r4, r5, r6],
    'phase_centres_relative_to_centroid_mm': centres,
    'phase_axis_depths_m': {k: p['burial_axis_depth_m']-v[1]/1000 for k,v in centres.items()},
    'trefoil_enclosing_diameter_mm': D*(1+2/sqrt(3)),
    'aluminium_effective_sigma_20_S_m': 1000/(p['max_dc_resistance_ohm_per_km']*pi*(r0/1000)**2),
    'peak_phase_voltage_V': p['line_voltage_rms_V']*sqrt(2/3),
    'peak_phase_current_A': p['reference_current_rms_A']*sqrt(2),
    'analytical_capacitance_uF_km': 2*pi*8.8541878128e-12*2.5/log(r2/r1)*1e9,
}
(HERE / 'derived_geometry.json').write_text(json.dumps(values, indent=2)+'\n')
macros = {'ContactThickness': r4-r3, 'CopperThickness': r5-r4,
          'CopperInnerRadius': r4, 'BundleDiameter': values['trefoil_enclosing_diameter_mm']}
tex = '% Generated by Source-code/section_1/calculate_geometry.py.\n'
tex += '\n'.join('\\newcommand{\\%s}{%.3f}' % (k,v) for k,v in macros.items())+'\n'
(ROOT / 'LaTeX/section_1/geometry_values.tex').write_text(tex)
print('Verified layer order, copper metal area, touching trefoil and burial geometry.')
