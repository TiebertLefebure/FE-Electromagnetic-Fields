"""Calculate the Section 1 dimensions and excitation. Lengths are in mm."""
import json
from math import hypot, log, pi, sqrt
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
cable = json.loads((HERE / 'cable_inputs.json').read_text())
materials = json.loads((HERE.parent / 'shared/materials.json').read_text())
assert cable['installation'] == 'direct_buried_touching_trefoil'

# Work outwards from the conductor. Each radius is a layer's outer boundary.
r_al = cable['conductor_diameter_mm'] / 2
r_semi_in = r_al + cable['inner_semiconductor_mm']
r_xlpe = r_semi_in + cable['xlpe_mm']
r_semi_out = r_xlpe + cable['outer_semiconductor_mm']

# Replace the copper wires by a ring with the same metal area:
# A_Cu = pi * (r_cu_out**2 - r_cu_in**2).
r_cu_out = cable['diameter_over_copper_mm'] / 2
r_cu_in = sqrt(r_cu_out*r_cu_out - cable['copper_area_mm2']/pi)
r_pe = cable['single_cable_diameter_mm'] / 2

# The gap from r_semi_out to r_cu_in is the assumed semiconducting contact
# region. The cover from r_cu_out to r_pe is treated as PE (see the report).
assert r_al < r_semi_in < r_xlpe < r_semi_out < r_cu_in < r_cu_out < r_pe, \
    'The cable layers must have increasing radii.'
assert abs(pi*(r_cu_out*r_cu_out-r_cu_in*r_cu_in) - cable['copper_area_mm2']) < 1e-9, \
    'The equivalent screen must preserve the copper area.'

# Touching trefoil: an equilateral triangle of side D, centred at the origin.
# Phase A is above B and C; y is positive upwards.
D = 2*r_pe
centres = {
    'A': [0, D/sqrt(3)],
    'B': [-D/2, -D/(2*sqrt(3))],
    'C': [D/2, -D/(2*sqrt(3))],
}
for first, second in [('A', 'B'), ('B', 'C'), ('C', 'A')]:
    a, b = centres[first], centres[second]
    spacing = hypot(a[0]-b[0], a[1]-b[1])
    assert abs(spacing-D) < 1e-9, 'Each pair of jackets must touch.'

# The burial depth is measured to the centroid. Convert mm to m here.
depths = {phase: cable['burial_axis_depth_m']-y/1000
          for phase, (x, y) in centres.items()}
assert all(depth > r_pe/1000 for depth in depths.values()), \
    'All cables must lie below the ground surface.'

# Keep the specified conductor diameter and match R = length/(sigma*area)
# to the datasheet's maximum DC resistance for a 1000 m length.
sigma_al = 1000/(cable['max_dc_resistance_ohm_per_km']*pi*(r_al/1000)**2)
voltage_peak = cable['line_voltage_rms_V']*sqrt(2/3)
current_peak = cable['reference_current_rms_A']*sqrt(2)

# Coaxial capacitance estimate with equipotential semiconducting screens.
# The XLPE is between r_semi_in and r_xlpe. Convert F/m to microfarads/km.
eps0 = materials['vacuum_permittivity_F_m']
eps_xlpe = materials['xlpe']['relative_permittivity']
capacitance = 2*pi*eps0*eps_xlpe/log(r_xlpe/r_semi_in)*1e9

values = {
    'installation': cable['installation'],
    'phase_radii_mm': [r_al, r_semi_in, r_xlpe, r_semi_out, r_cu_in, r_cu_out, r_pe],
    'phase_centres_relative_to_centroid_mm': centres,
    'phase_axis_depths_m': depths,
    'trefoil_enclosing_diameter_mm': D*(1+2/sqrt(3)),
    'aluminium_effective_sigma_20_S_m': sigma_al,
    'peak_phase_voltage_V': voltage_peak,
    'peak_phase_current_A': current_peak,
    'analytical_capacitance_uF_km': capacitance,
}
(HERE / 'derived_geometry.json').write_text(json.dumps(values, indent=2)+'\n')

# Export the calculated dimensions used in the LaTeX table.
macros = {
    'ContactThickness': r_cu_in-r_semi_out,
    'CopperThickness': r_cu_out-r_cu_in,
    'CopperInnerRadius': r_cu_in,
    'BundleDiameter': values['trefoil_enclosing_diameter_mm'],
}
tex = '% Generated by Source-code/section_1/calculate_geometry.py.\n'
for name, value in macros.items():
    tex += '\\newcommand{\\%s}{%.3f}\n' % (name, value)
(ROOT / 'LaTeX/section_1/geometry_values.tex').write_text(tex)
print('Geometry checks passed. Wrote derived_geometry.json and geometry_values.tex.')
